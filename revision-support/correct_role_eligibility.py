"""Versioned role-predicate correction; historical derived inputs stay immutable."""
from pathlib import Path
import hashlib,json
import numpy as np
import pandas as pd
from claim_logic import parse_compact_expression,contains_role_predicate,unique_index,verify_pair_inventory
P=Path(__file__).resolve().parent
OUT=P/'corrections/role-predicate-v2';OUT.mkdir(parents=True,exist_ok=True)
legacy=pd.read_csv(P/'exposure-pairs.csv')
keys=['condition_id','task_id','repetition','expression','recipient']
rows=[];inputs=[P/'exposure-pairs.csv',P/'debate-features.csv',P/'paper-auc.csv']
for size,name in [(6,'claims.csv'),(8,'claims-size8.csv')]:
 path=P/'control-inputs'/name;inputs.append(path)
 d=pd.read_csv(path).fillna('');unique_index(d.to_dict('records'),('claim_uid',),f'size{size} claims')
 d=d[d.commitment.isin(['assert','endorse'])].copy()
 d['expr']=d.effective_expression.where(d.effective_expression.ne(''),d.expression)
 old_expected={}
 for key,g in d.groupby(['condition_id','task_id','repetition']):
  for expr,gg in g.groupby('expr'):
   if gg.stage_order.min()!=0:continue
   origin=gg[gg.stage_order.eq(0)];kind=origin.information_type.iloc[0]
   if kind not in ['truth_aligned','misleading']:continue
   if contains_role_predicate(parse_compact_expression(expr)):continue
   for agent in ['agent-1','agent-2','agent-3']:
    if agent in set(origin.agent_id):continue
    took=int(any((gg.agent_id==agent)&gg.stage_order.gt(0)&gg.stage_order.lt(10010)))
    row=dict(zip(keys,[*key,expr,agent]));row.update(dataset=f'size{size}',information_type=kind,adopted=took);rows.append(row)
    if 'ROLE(' not in expr:old_expected[(*key,expr,agent)]=(kind,took)
 # The old policy is checked explicitly; this does not certify it as intended.
 verify_pair_inventory(legacy[legacy.dataset.eq(f'size{size}')].to_dict('records'),old_expected)
e=pd.DataFrame(rows)[list(legacy.columns)].sort_values(['dataset',*keys]).reset_index(drop=True)
unique_index(e.to_dict('records'),keys,'corrected exposure inventory')
e.to_csv(OUT/'exposure-pairs.csv',index=False)
f=pd.read_csv(P/'debate-features.csv',float_precision='round_trip')
unique_index(f.to_dict('records'),('condition_id','task_id','repetition','dataset'),'debate features')
for i,r in f.iterrows():
 sub=e[e.condition_id.eq(r.condition_id)&e.task_id.eq(r.task_id)&e.repetition.eq(r.repetition)&e.dataset.eq(r.dataset)]
 for kind,label in [('truth_aligned','true'),('misleading','false')]:
  a=sub[sub.information_type.eq(kind)];f.at[i,f'eligible_{label}_pairs']=len(a);f.at[i,f'adopted_{label}_pairs']=a.adopted.sum()
  f.at[i,f'uptake_{label}']=a.adopted.mean() if len(a) else np.nan
 f.at[i,'false_resistance']=1-f.at[i,'uptake_false'];f.at[i,'selectivity']=f.at[i,'uptake_true']-f.at[i,'uptake_false']
f.to_csv(OUT/'debate-features.csv',index=False)
a=pd.read_csv(P/'paper-auc.csv')
for i,r in a.iterrows():
 sub=f[f[r.feature].notna()];ss=sub[sub.operational_final_correct.eq(1)];ff=sub[sub.operational_final_correct.eq(0)]
 a.at[i,'n']=len(sub)
 for mode in ['pooled','within_condition']:
  vals=[];contributors=set()
  for si,s in ss.iterrows():
   for fi,t in ff.iterrows():
    if mode=='within_condition' and s.stratum!=t.stratum:continue
    vals.append(float(s[r.feature]>t[r.feature])+.5*float(s[r.feature]==t[r.feature]));contributors.update([si,fi])
  a.at[i,'auc_'+mode]=np.mean(vals)
  if mode=='within_condition':a.at[i,'n_within_contributing']=len(contributors);a.at[i,'within_comparison_pairs']=len(vals)
 # Intervals are regenerated by reconcile_statistics.py, never inherited.
 for col in ['pooled_ci_low','pooled_ci_high','within_ci_low','within_ci_high']:a.at[i,col]=np.nan
a.to_csv(OUT/'paper-auc.csv',index=False)
oldkeys=set(map(tuple,legacy[keys].to_numpy()));added=e[[tuple(r) not in oldkeys for r in e[keys].to_numpy()]]
added.to_csv(OUT/'added-exposures.csv',index=False)
manifest={'version':'role-predicate-v2','reason':'Exclude role_is AST nodes, not SAME_ROLE relational predicates. No translations changed.','legacy_counts':legacy.groupby('dataset').size().to_dict(),'corrected_counts':e.groupby('dataset').size().to_dict(),'added_counts':added.groupby('dataset').size().to_dict(),'inputs_sha256':{str(p.relative_to(P)):hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs}}
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n');print(json.dumps(manifest,indent=2))
